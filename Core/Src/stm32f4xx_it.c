/**
  * @brief This function handles USART1 global interrupt.
  */
void USART1_IRQHandler(void)
{
  /* USER CODE BEGIN USART1_IRQn 0 */
  if (__HAL_UART_GET_FLAG(&huart1, UART_FLAG_IDLE) != RESET)
  {
      __HAL_UART_CLEAR_IDLEFLAG(&huart1);

      HAL_UART_DMAStop(&huart1);

      vision_rx_len = (uint16_t)(VISION_BUF_LEN - __HAL_DMA_GET_COUNTER(&hdma_usart1_rx));

      Vision_OnRxIdle(vision_rx_len);

      HAL_UART_Receive_DMA(&huart1, (uint8_t *)vision_rx_buf, VISION_BUF_LEN);
  }
  /* USER CODE END USART1_IRQn 0 */
  HAL_UART_IRQHandler(&huart1);
  /* USER CODE BEGIN USART1_IRQn 1 */

  /* USER CODE END USART1_IRQn 1 */
}

/**
  * @brief This function handles USART3 global interrupt.
  */
void USART3_IRQHandler(void)
{
  /* USER CODE BEGIN USART3_IRQn 0 */
  if (__HAL_UART_GET_FLAG(&huart3, UART_FLAG_IDLE) != RESET)
  {
      uint16_t len;

      __HAL_UART_CLEAR_IDLEFLAG(&huart3);

      /* 【重要】这里绝对不能调 HAL_UART_DMAStop()：
       * 它会同时停掉“接收”和“发送”两路 DMA。驱动器对每条运动指令
       * 都会回一个应答，应答一到就进这个 IDLE 分支，于是正在发送的
       * 那条指令当场被掐断——闭环每帧都在发指令，结果一条都发不完整，
       * 平台纹丝不动。所以下面只重启接收 DMA，一个字节都不碰发送。 */
      len = (uint16_t)(EMM_RX_BUF_LEN - __HAL_DMA_GET_COUNTER(&hdma_usart3_rx));

      emm_rx_len = len;

      Emm_V5_OnRxIdle(len);

      __HAL_DMA_DISABLE(&hdma_usart3_rx);
      __HAL_DMA_CLEAR_FLAG(&hdma_usart3_rx,
                           __HAL_DMA_GET_TC_FLAG_INDEX(&hdma_usart3_rx));
      hdma_usart3_rx.Instance->NDTR = EMM_RX_BUF_LEN;
      __HAL_DMA_ENABLE(&hdma_usart3_rx);
  }
  /* USER CODE END USART3_IRQn 0 */
  HAL_UART_IRQHandler(&huart3);
  /* USER CODE BEGIN USART3_IRQn 1 */

  /* USER CODE END USART3_IRQn 1 */
}

